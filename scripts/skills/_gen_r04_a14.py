def body(when, inputs, steps, outputs, notes):
    parts = []
    parts.append("## 何时使用\n" + when)
    parts.append("## 输入\n" + "\n".join("- " + i for i in inputs))
    parts.append("## 步骤\n" + "\n".join(f"{idx+1}. {s}" for idx, s in enumerate(steps)))
    parts.append("## 输出\n" + outputs)
    parts.append("## 注意事项\n" + notes)
    return "\n\n".join(parts)


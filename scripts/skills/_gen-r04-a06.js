// Helper to build a SKILL.md body
function body({ when, inputs, steps, outputs, notes }) {
  const stepLines = steps.map((s, i) => `${i + 1}. ${s}`).join('\n');
  const inputLines = inputs.map((s) => `- ${s}`).join('\n');
  const outputLines = outputs.map((s) => `- ${s}`).join('\n');
  const noteLines = notes.map((s) => `- ${s}`).join('\n');
  return [
    '## 何时使用',
    when,
    '',
    '## 输入',
    inputLines,
    '',
    '## 步骤',
    stepLines,
    '',
    '## 输出',
    outputLines,
    '',
    '## 注意事项',
    noteLines,
  ].join('\n');
}


// Validation
let totalSkills = 0;
for (const r of result) {
  const names = new Set();
  for (const s of r.skills) {
    if (names.has(s.name)) throw new Error('dup name in ' + r.role + ': ' + s.name);
    names.add(s.name);
    if (s.body.length < 300) throw new Error('body too short: ' + r.role + '/' + s.name + ' = ' + s.body.length);
    if (s.body.includes('"')) throw new Error('unescaped quote in ' + r.role + '/' + s.name);
    for (const seg of ['## 何时使用', '## 输入', '## 步骤', '## 输出', '## 注意事项']) {
      if (!s.body.includes(seg)) throw new Error('missing seg ' + seg + ' in ' + r.role + '/' + s.name);
    }
    totalSkills++;
  }
  const paidFalse = r.skills.filter((s) => s.paid === false).length;
  if (paidFalse !== 2) throw new Error('paid:false count != 2 for ' + r.role + ': ' + paidFalse);
  if (r.skills.length !== 8) throw new Error('skill count != 8 for ' + r.role);
}


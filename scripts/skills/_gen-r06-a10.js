// build output
const out = roles.map(r => ({
  role: r.role,
  category: r.category,
  skills: r.skills.map(s => ({
    name: s.name,
    desc: s.desc,
    paid: s.paid,
    body: body(s.when, s.inputs, s.steps, s.outputs, s.notes),
  })),
}));

// sanity checks
let totalSkills = 0;
for (const r of out) {
  if (r.skills.length !== 8) throw new Error(`role ${r.role} has ${r.skills.length} skills`);
  const names = new Set(r.skills.map(s => s.name));
  if (names.size !== 8) throw new Error(`role ${r.role} has duplicate skill names`);
  const paidFalse = r.skills.filter(s => s.paid === false).length;
  if (paidFalse !== 2) throw new Error(`role ${r.role} has ${paidFalse} free skills`);
  for (const s of r.skills) {
    if (s.body.length < 300) throw new Error(`skill ${r.role}/${s.name} body too short: ${s.body.length}`);
    for (const seg of ['## 何时使用', '## 输入', '## 步骤', '## 输出', '## 注意事项']) {
      if (!s.body.includes(seg)) throw new Error(`skill ${r.role}/${s.name} missing ${seg}`);
    }
    if (s.body.includes('"')) throw new Error(`skill ${r.role}/${s.name} contains raw double quote`);
    totalSkills++;
  }
}


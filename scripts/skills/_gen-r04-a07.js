// 构造每个技能的完整 Markdown body（不含半角双引号，统一用中文引号或单引号）
function md(parts) {
  const { when, inputs, steps, outputs, notes } = parts;
  const sec = (title, lines) => `## ${title}\n` + lines.join('\n');
  const stepLines = steps.map((s, i) => `${i + 1}. ${s}`);
  return [
    sec('何时使用', when),
    '',
    sec('输入', inputs.map((x) => `- ${x}`)),
    '',
    sec('步骤', stepLines),
    '',
    sec('输出', outputs.map((x) => `- ${x}`)),
    '',
    sec('注意事项', notes.map((x) => `- ${x}`)),
  ].join('\n');
}


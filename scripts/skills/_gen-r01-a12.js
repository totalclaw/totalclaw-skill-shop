function skill(name, desc, paid, when, inputs, steps, output, notes) {
  const body =
    `## 何时使用\n${when}\n\n` +
    `## 输入\n${inputs.map(i => `- ${i}`).join('\n')}\n\n` +
    `## 步骤\n${steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n\n` +
    `## 输出\n${output}\n\n` +
    `## 注意事项\n${notes}`;
  return { name, desc, paid, body };
}


// assemble output
const out = inputs.map(item => {
  const skills = data[item.role];
  if (!skills || skills.length !== 8) throw new Error('skill count error for ' + item.role + ': ' + (skills ? skills.length : 'none'));
  const names = new Set();
  return {
    role: item.role,
    category: item.category,
    skills: skills.map(s => {
      if (names.has(s.name)) throw new Error('dup name ' + s.name);
      names.add(s.name);
      if (s.b.length < 300) throw new Error('body too short: ' + s.name + ' len=' + s.b.length);
      if (s.b.indexOf('"') !== -1) throw new Error('unescaped quote in ' + s.name);
      return { name: s.name, desc: s.desc, paid: s.paid, body: s.b };
    })
  };
});


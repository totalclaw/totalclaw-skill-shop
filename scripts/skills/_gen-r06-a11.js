// helper to build a skill body
function body(when, inputsList, steps, outputs, notes) {
  let md = '';
  md += '## 何时使用\n' + when + '\n\n';
  md += '## 输入\n';
  for (const i of inputsList) md += '- ' + i + '\n';
  md += '\n## 步骤\n';
  steps.forEach((s, idx) => { md += (idx + 1) + '. ' + s + '\n'; });
  md += '\n## 输出\n';
  for (const o of outputs) md += '- ' + o + '\n';
  md += '\n## 注意事项\n';
  for (const n of notes) md += '- ' + n + '\n';
  return md;
}


function applyBulkZh(text) {
  let out = text;
  const parts = out.split(/(```[\s\S]*?```)/);
  for (let i = 0; i < parts.length; i += 2) {
    let chunk = parts[i];
    for (const [from, to] of REPLACEMENTS) {
      chunk = chunk.split(from).join(to);
    }
    parts[i] = chunk;
  }
  return parts.join('');
}


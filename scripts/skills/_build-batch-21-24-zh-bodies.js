function readEn(skillId) {
  const fname = skillId.replace(/[:~]/g, '_') + '.en.txt';
  return fs.readFileSync(path.join(SRC, fname), 'utf8');
}

function translateKeepingCode(en, pairs) {
  const blocks = en.split(/(```[\s\S]*?```)/g);
  return blocks
    .map((block) => {
      if (block.startsWith('```')) return block;
      let t = block;
      for (const [from, to] of pairs) {
        if (from instanceof RegExp) t = t.replace(from, to);
        else t = t.split(from).join(to);
      }
      return t;
    })
    .join('');
}

function escTpl(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}


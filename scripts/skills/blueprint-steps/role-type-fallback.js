function roleType(profile) {
  const t = profile.name;
  if (isTestRoleTitle(t)) return 'qa';
  if (isSecurityRoleTitle(t)) return 'security';
  if (isFinanceRoleTitle(t)) return 'finance';
  if (isRnDEngineerTitle(t)) return 'rnd';
  if (isDevRoleTitle(t)) return 'dev';
  if (isDesignRoleTitle(t)) return 'design';
  if (isHardwareEngTitle(t)) return 'eng';
  if (/经理|总监|主管|负责人|主任|VP|总裁|CEO|CTO|CFO|COO|行长|厂长|矿长/.test(t)) return 'mgmt';
  if (/销售|商务|客户成功|BD|渠道|招商|拓展/.test(t)) return 'sales';
  if (/运营|客服|支持|售后|坐席|主播|内容|编辑|文案|新媒体/.test(t)) return 'ops';
  return 'general';
}

function resolveRoleTypePack(profile, suffix) {
  const type = roleType(profile);
  const lib = TYPE_SUFFIX_STEPS[type] || TYPE_SUFFIX_STEPS.general;
  const lines = lib[suffix] || lib._default || TYPE_SUFFIX_STEPS.general[suffix];
  if (!lines) return null;
  return {
    domainId: `role-type:${type}`,
    steps: lines.map((l) => fill(l, profile)),
    inputs: null,
    example: null,
  };
}

module.exports = { roleType, resolveRoleTypePack, TYPE_SUFFIX_STEPS, SUFFIXES };

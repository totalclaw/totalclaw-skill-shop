function findDomain(category) {
  for (const d of DOMAINS) {
    if (d.categories.some((re) => re.test(category))) return d;
  }
  return null;
}

function resolvePack(profile, suffix) {
  const domain = findDomain(profile.category);
  if (!domain) return null;
  const pack = domain.packs[suffix];
  if (!pack) return null;
  return {
    domainId: domain.id,
    steps: steps(profile, pack.steps),
    inputs: pack.inputs ? pack.inputs.map((i) => fill(i, profile)) : null,
    example: pack.example
      ? { input: fill(pack.example.input, profile), output: fill(pack.example.output, profile) }
      : null,
  };
}

function listPilotCategories() {
  const set = new Set();
  for (const d of DOMAINS) {
    // categories are regex; caller uses match at runtime
    set.add(d.id);
  }
  return DOMAINS;
}


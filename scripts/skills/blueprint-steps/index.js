// 其余 8 个样板品类：用紧凑 packs 生成（步骤域化、去通用套话）
function compactDomain(id, categories, verbs) {
  const packs = {};
  for (const suffix of SUFFIXES) {
    const v = verbs[suffix] || verbs._default;
    packs[suffix] = {
      steps: v.steps,
      inputs: v.inputs,
      example: v.example,
    };
  }
  return { id, categories, packs };
}


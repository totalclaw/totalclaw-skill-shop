function fill(tpl, p) {
  return String(tpl)
    .replace(/\{name\}/g, p.name)
    .replace(/\{cat\}/g, p.category)
    .replace(/\{duty\}/g, (p.enrichedDuties || p.responsibilities || [])[0] || `${p.name}核心工作`);
}

function steps(p, lines) {
  return lines.map((l) => fill(l, p));
}

